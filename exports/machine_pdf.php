';


// ==============================
// TABLE DATA
// ==============================

if (
    $result &&
    mysqli_num_rows($result) > 0
) {

    while ($row = mysqli_fetch_assoc($result)) {

        $html .= '

        <tr>

        <td>' .
        htmlspecialchars($row['asset_number']) .
        '</td>

        <td>' .
        htmlspecialchars($row['customer_name']) .
        '</td>

        <td>' .
        htmlspecialchars($row['brand']) .
        '</td>

