<?php

session_start();

require_once("../includes/permissions.php");
requireRole(['Manager']);

if (!isset($_SESSION['username'])) {
    header("Location: ../auth/login.php");
    exit();
}

require_once("../config/db.php");
require_once("../vendor/autoload.php");

use Dompdf\Dompdf;
use Dompdf\Options;


// ==============================
// COMPANY SETTINGS
// ==============================

$settings_result = mysqli_query(
    $conn,
    "SELECT * FROM settings WHERE id=1"
);

$settings = mysqli_fetch_assoc($settings_result);

$company_name = $settings['company_name'] ?? "G3 Systems";
$company_phone = $settings['company_phone'] ?? "";
$company_email = $settings['company_email'] ?? "";
$company_address = $settings['company_address'] ?? "";


// ==============================
// SEARCH
// ==============================

$search = "";

if (isset($_GET['search'])) {

    $search = mysqli_real_escape_string(
        $conn,
        $_GET['search']
    );

}


// ==============================
// MACHINE DATA
// ==============================

$sql = "

SELECT
    machines.*,
    customers.customer_name

FROM machines

LEFT JOIN customers
    ON machines.customer_id = customers.id

WHERE

machines.asset_number LIKE '%$search%'

OR customers.customer_name LIKE '%$search%'

OR machines.machine_model LIKE '%$search%'

OR machines.brand LIKE '%$search%'

OR machines.serial_number LIKE '%$search%'

ORDER BY machines.asset_number ASC

";

$result = mysqli_query($conn, $sql);


// ==============================
// PDF HTML
// ==============================

$html = '

<!DOCTYPE html>

